import type { Metadata } from 'next';
import { site } from '@/data/site';

/** Open Graph locale codes for the site's languages. */
const OG_LOCALE = { en: 'en_US', cs: 'cs_CZ' } as const;

interface PageMetadataInput {
  locale: string;
  /** Path below the locale, '' for the home page, e.g. '/privacy'. */
  path?: string;
  title: string;
  description: string;
}

/**
 * Title, description, canonical, hreflang, Open Graph and Twitter tags for one page in one locale.
 * Metadata objects replace (not merge) their parents', so every page passes through here for a
 * complete set. Relative URLs resolve against `metadataBase` from the locale layout.
 */
export function pageMetadata({ locale, path = '', title, description }: PageMetadataInput): Metadata {
  const url = `/${locale}${path}`;
  // The card is generated by src/app/[locale]/opengraph-image.tsx. Listed explicitly because a page's
  // own `openGraph` replaces the parent's, which is where Next would otherwise inject it.
  const image = { url: `/${locale}/opengraph-image`, width: 1200, height: 630 };
  const other = locale === 'cs' ? 'en' : 'cs';

  return {
    title,
    description,
    alternates: {
      canonical: url,
      languages: {
        en: `/en${path}`,
        cs: `/cs${path}`,
        // The bare root redirects by Accept-Language, which is what x-default is for; other pages
        // have no such entry point, so x-default is the English version.
        'x-default': path ? `/en${path}` : '/',
      },
    },
    openGraph: {
      type: 'website',
      siteName: site.url.replace('https://', ''),
      locale: OG_LOCALE[locale as keyof typeof OG_LOCALE] ?? OG_LOCALE.en,
      alternateLocale: OG_LOCALE[other],
      url,
      title,
      description,
      images: [image],
    },
    twitter: { card: 'summary_large_image', title, description, images: [image.url] },
  };
}
